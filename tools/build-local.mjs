// Builds dist/lunar-lookout.js: the whole app as ONE classic script.
//
// Browsers refuse to load ES modules from file:// pages, so when someone opens
// index.html by double-clicking it, index.html loads this bundle instead of
// js/main.js. The live site keeps using the modules directly (no build step).
//
//   npm run build        regenerate the bundle after changing anything in js/
//   npm test             fails if the committed bundle is out of date
import * as esbuild from 'esbuild';
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export async function buildBundle() {
  const r = await esbuild.build({
    entryPoints: [root + 'js/main.js'],
    bundle: true, format: 'iife', write: false, minify: false, legalComments: 'inline',
    target: ['es2019'], charset: 'utf8',
    alias: { three: root + 'vendor/three.module.min.js' },
    banner: { js: '/* Lunar Lookout: generated by tools/build-local.mjs from js/*.js. Do not edit; run `npm run build`. */' },
    logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = await buildBundle();
  const path = root + 'dist/lunar-lookout.js';
  let old = ''; try { old = readFileSync(path, 'utf8'); } catch (e) { /* first build */ }
  writeFileSync(path, out);
  console.log(`${old === out ? 'unchanged' : 'wrote'} dist/lunar-lookout.js (${(out.length / 1024).toFixed(0)} KB)`);
}
